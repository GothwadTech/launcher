/**
 * Native Android Drawable that renders a vector path data string.
 * High performance, zero Compose overhead.
 */
class VectorPathDrawable(
    private val path: Path,
    private val viewportWidth: Float = 24f,
    private val viewportHeight: Float = 24f,
    var tintColor: Int = android.graphics.Color.WHITE,
) : Drawable() {

    private val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
        style = Paint.Style.FILL
        color = tintColor
    }

    fun setColor(color: Int) {
        if (tintColor != color) {
            tintColor = color
            paint.color = color
            invalidateSelf()
        }
    }

    override fun draw(canvas: Canvas) {
        val bounds = bounds
        val w = bounds.width().toFloat()
        val h = bounds.height().toFloat()
        if (w <= 0f || h <= 0f) return

        canvas.save()
        canvas.translate(bounds.left.toFloat(), bounds.top.toFloat())
        canvas.scale(w / viewportWidth, h / viewportHeight)
        canvas.drawPath(path, paint)
        canvas.restore()
    }

    override fun setAlpha(alpha: Int) {
        paint.alpha = alpha
        invalidateSelf()
    }

    override fun setColorFilter(colorFilter: ColorFilter?) {
        paint.colorFilter = colorFilter
        invalidateSelf()
    }

    @Deprecated("Deprecated in Java")
    override fun getOpacity(): Int = PixelFormat.TRANSLUCENT
}

